# build.ps1 - build Charker for Windows with plain Go. No Bun, no npm, no NSIS.
#
#   .\build.ps1                 dev build   -> build\charker-dev.exe
#   .\build.ps1 -Mode release   release exe -> build\Charker.exe
#   .\build.ps1 -Mode release -Version 0.2.0
#
# The dev build keeps the console (logs are visible), the WebView2 inspector
# and the charkerdev hooks in dev.go (data redirect into the workspace, mock
# switch, auto-quit, screenshots). The release build is a GUI exe with the
# production flag (no inspector) per docs/port/spec-mygo.md §8.2.
#
# An exe icon/version resource/manifest would need a .syso generated by
# `go run github.com/egoist/mygo/cmd/mygo build` (mygo.json + NSIS, which
# downloads NSIS on first use — not available offline), so plain `go build`
# produces an icon-less exe for now; see docs/port/spec-mygo.md §8.3.
[CmdletBinding()]
param(
  [ValidateSet('dev', 'release')] [string]$Mode = 'dev',
  [string]$Version = '0.1.0',
  [string]$OutDir = 'build'
)
$ErrorActionPreference = 'Stop'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$go = Join-Path (Split-Path -Parent $here) 'tools\go.cmd'   # workspace toolchain
$out = Join-Path $here $OutDir
New-Item -ItemType Directory -Force -Path $out | Out-Null

Push-Location $here
try {
  if ($Mode -eq 'dev') {
    $exe = Join-Path $out 'charker-dev.exe'
    & $go build -trimpath -tags charkerdev -o $exe .
    if ($LASTEXITCODE -ne 0) { throw "go build failed ($LASTEXITCODE)" }
    Write-Host "built $exe (dev: console, inspector, dev.log)"
  }
  else {
    $exe = Join-Path $out 'Charker.exe'
    $ld = @(
      '-s', '-w', '-H=windowsgui',
      '-X', 'github.com/egoist/mygo.production=1',
      '-X', 'github.com/egoist/mygo.packageName=Charker',
      '-X', "github.com/egoist/mygo.packageVersion=$Version",
      '-X', 'github.com/egoist/mygo.packageIdentifier=com.example.charker',
      '-X', "main.version=$Version"
    ) -join ' '
    & $go build -trimpath -ldflags $ld -o $exe .
    if ($LASTEXITCODE -ne 0) { throw "go build failed ($LASTEXITCODE)" }
    Write-Host "built $exe (release: GUI subsystem, production, version $Version)"
  }
}
finally {
  Pop-Location
}
